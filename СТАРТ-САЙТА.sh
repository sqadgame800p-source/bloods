#!/bin/bash
# ================================================
# СТАРТ САЙТА «ДЕЛО В МЯСЕ»
# Запускает мини-сервер и открывает сайт в браузере
# Двойной клик по этому файлу — и сайт работает как настоящий.
# ================================================

# Переходим в папку, где лежит этот файл
cd "$(dirname "$0")"

# Если сервер (порт 8000) ещё не запущен — запускаем его тихо в фоне
if ! curl -s -o /dev/null http://localhost:8000; then
    nohup python3 -m http.server 8000 > /tmp/delovmyase-server.log 2>&1 &
    sleep 1
fi

# Открываем сайт в браузере
xdg-open http://localhost:8000/index.html
